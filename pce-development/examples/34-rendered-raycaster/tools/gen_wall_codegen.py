#!/usr/bin/env python3
"""Generate bounded HuC6280 *instructions* for scaled wall BAT column writes.

PCEdev's vertical-texture reader idea: texture data are fixed ROM bytes, and
code generation embeds the scaled V offsets into LDA absolute,X instructions.
X chooses only one of 40 material/U variants; per-pixel loops, table pointer
increment, coordinate arithmetic, and C stores are absent in the hot path.

Each entry writes exactly EIGHT consecutive 16-bit BAT words using the VDC's
128-word autoincrement. Four paired texels are read, each stored twice, which
is EXACTLY equivalent to the original wall_tex_v[d][(y-top)>>1] sampling.
The caller masks IRQs for one eight-word entry only and selects VDC register
2 and the vertical address beforehand. No generated code changes the BAT mode.

The same kernel is reused for repeated wall heights to control HuCard size.
"""
from pathlib import Path
import argparse
from gen_wall_pairs import pair

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT/'src'/'wall_codegen.S'
HEIGHTS = [max(12,min(116,360//(d+2))) for d in range(33)]
MAX_SEGMENTS = 16

def texture_v(height, offset):
    return ((offset//2)*32)//height

def generate():
    a=['/* Generated by tools/gen_wall_codegen.py; do not edit. */',
       '/* One 8-word/16-byte vertical burst per invocation. X=material*8+U. */',
       '.section .text.ray_codegen,"ax",@progbits',
       '.global ray_codegen_emit', '.type ray_codegen_emit,@function',
       '.extern ray_codegen_variant,ray_codegen_target',
       'ray_codegen_emit:', '    phx', '    ldx ray_codegen_variant',
       '    jmp (ray_codegen_target)', '.Ldone:', '    plx', '    rts',
       '.size ray_codegen_emit, .-ray_codegen_emit',
       '.section .rodata.ray_codegen,"a",@progbits',
       '.global ray_codegen_handlers', 'ray_codegen_handlers:']
    for d,h in enumerate(HEIGHTS):
        addresses=[f'ray_codegen_h{h}_s{s}' if s*8+8<=h else '0' for s in range(MAX_SEGMENTS)]
        a.extend('    .word '+','.join(addresses[i:i+8]) for i in (0,8))
    a += ['/* 16 fixed vertical texture offsets x 40 material/U combinations. */',
          '/* The 40-byte stride is computed offline, never by the 6280. */',
          '.balign 256','ray_codegen_pixels:']
    for v in range(16):
        values=[pair(style,u,v) for style in range(5) for u in range(8)]
        a.append('    .byte '+','.join(f'${x:02x}' for x in values))
    a+=['.section .text.ray_codegen_paths,"ax",@progbits']
    for h in sorted(set(HEIGHTS),reverse=True):
        for seg in range(h//8):
            label=f'ray_codegen_h{h}_s{seg}'
            a+= [f'.global {label}',f'.type {label},@function',f'{label}:']
            # Each texture V is held for two output rows. Explicit instructions
            # (not a loop) let the assembler encode the ROM source address.
            for offset in range(seg*8,seg*8+8,2):
                v=texture_v(h,offset)
                a+= [f'    lda ray_codegen_pixels+{v*40},x',
                      '    sta $0002', '    st2 #$f2',
                      '    sta $0002', '    st2 #$f2']
            a.append('    jmp .Ldone')
            a.append(f'.size {label}, .-{label}')
    a.append('')
    return '\n'.join(a)

def validate():
    assert len(HEIGHTS)==33
    assert len({(h,s) for h in HEIGHTS for s in range(h//8)})<110
    assert all(0<=texture_v(h,k)<16 for h in HEIGHTS for k in range(h))
    # Reproduce each of the eight exact pixel-pairs for all depths and
    # materials independently of the assembly string generation.
    for h in HEIGHTS:
        for seg in range(h//8):
            for style in range(5):
                for u in range(8):
                    slow=[pair(style,u,texture_v(h,k)) for k in range(seg*8,seg*8+8)]
                    fast=[pair(style,u,texture_v(h,k)) for off in range(seg*8,seg*8+8,2) for k in (off,off+1)]
                    if slow!=fast: raise AssertionError('generated kernel mismatch')

def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true')
    args=ap.parse_args();validate();expected=generate()
    if args.check:
        if not OUT.is_file() or OUT.read_text()!=expected:
            ap.error('wall_codegen.S stale, run tools/gen_wall_codegen.py')
        print('generated wall microcode is current and equivalent across 33 distances, 40 variants')
    else:
        OUT.write_text(expected)
        print('wrote',OUT,'bytes:',len(expected),'unique heights:',len(set(HEIGHTS)))
if __name__=='__main__':main()
