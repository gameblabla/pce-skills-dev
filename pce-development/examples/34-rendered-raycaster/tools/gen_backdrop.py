#!/usr/bin/env python3
"""Generate compact arithmetic-backed BAT sky/ground texels.

The prior static 14-row checkerboard used four hard sky bands and 16-pixel
floor blocks. A procedural backing pixel costs no extra per-frame VRAM words,
and avoids an enormous ROM table for ordered-dithered 128x128 artwork.
No framebuffer is kept; this helper runs only on initial VRAM fill and when
restoring previously covered floor/sky behind a changed wall column.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT/'src'/'backdrop_words.h'

# Four-way Bayer order with horizontal decorrelation for the paired pixels.
BAYER = ((0, 8, 2, 10), (12, 4, 14, 6), (3, 11, 1, 9), (15, 7, 13, 5))


def sky(y, pixel_x):
    band = y >> 4
    if band >= 3:
        return 3
    # A short 4-row ordered transition avoids a noisy full-screen dither.
    return band + ((y & 15) >= 12 and BAYER[y & 3][pixel_x & 3] < ((y & 3) + 1) * 4)


def ground(u, v):
    # Perspective checker pattern with fine stone irregularity and thin grout.
    # Keep the original earth and mortar slots (5, 6, 7), so texture colours
    # retain their 16-colour palette assignment without palette animation.
    if (u & 31) == 0 or (v & 31) == 0:
        return 4
    tile = ((u >> 4) ^ (v >> 4)) & 1
    # Freckle individual stones, not entire giant 16-texel slabs.
    if ((u ^ (v >> 1)) & 31) == 0:
        return 5
    return 5 if tile else 6


def backdrop(y, pair):
    if y < 64:
        return 0xf200 | (sky(y, pair * 2) << 4) | sky(y, pair * 2 + 1)
    shift = 0 if y < 66 else 4 if y < 73 else 3 if y < 82 else 2 if y < 101 else 1
    fu = ((pair << shift) + 28) & 255
    fv = ((y << shift) + 28) & 255
    step = 8 if shift == 4 else (1 << (shift - 1)) if shift else 1
    return 0xf200 | (ground(fu, fv) << 4) | ground((fu + step) & 255, fv)


def generate():
    # Table stores only the backdrop's true horizontal period per row.
    # Dithered sky repeats every two BAT pairs. Floor repeats every
    # 32 >> floor_shift[y] pairs; the largest period is 32.
    shifts=[0 if y<66 else 4 if y<73 else 3 if y<82 else 2 if y<101 else 1 for y in range(128)]
    periods=[2 if y<64 else 32 >> shifts[y] for y in range(128)]
    offsets=[]
    packed=[]
    for y, period in enumerate(periods):
        offsets.append(len(packed))
        packed.extend(backdrop(y, pair) for pair in range(period))
    assert len(packed)==826
    c = [
        '/* Generated by tools/gen_backdrop.py; do not edit. */',
        '#ifndef RAY_BACKDROP_WORDS_H',
        '#define RAY_BACKDROP_WORDS_H',
        '/* 4x4 ordered dithering, one native BAT word = two 4-bit colours. */',
        'static const uint8_t ray_sky_bayer[16] = {',
        '    ' + ','.join(str(v) for row in BAYER for v in row),
        '};',
        'static inline uint8_t ray_sky_color(uint8_t y,uint8_t x) {',
        '    uint8_t base=(uint8_t)(y>>4);',
        '    if(base>=3u)return 3u;',
        '    uint8_t order=ray_sky_bayer[((y&3u)<<2)|(x&3u)];',
        '    uint8_t phase=(uint8_t)(y&15u);',
        '    return (uint8_t)(base+(phase>=12u && order<((uint8_t)((phase&3u)+1u)<<2)));',
        '}',
        'static inline uint8_t ray_ground_color(uint8_t u,uint8_t v) {',
        '    if((u&31u)==0u || (v&31u)==0u)return 4u;',
        '    if((((uint8_t)(u^(v>>1)))&31u)==0u)return 5u;',
        '    return (uint8_t)((((u>>4)^(v>>4))&1u)?5u:6u);',
        '}',
        'static inline uint16_t ray_backdrop_word(uint8_t y,uint8_t pair) {',
        '    uint8_t a,b;',
        '    if(y<64u) {',
        '        a=ray_sky_color(y,(uint8_t)(pair<<1));',
        '        b=ray_sky_color(y,(uint8_t)((pair<<1)+1u));',
        '    } else {',
        '        uint8_t shift=floor_shift[y];',
        '        uint8_t fu=(uint8_t)((pair<<shift)+28u);',
        '        uint8_t fv=(uint8_t)((y<<shift)+28u);',
        '        uint8_t step=shift==4u?8u:(shift?(uint8_t)(1u<<(shift-1u)):1u);',
        '        a=ray_ground_color(fu,fv);',
        '        b=ray_ground_color((uint8_t)(fu+step),fv);',
        '    }',
        '    return (uint16_t)(0xf200u|((uint16_t)a<<4)|b);',
        '}',
        '#ifndef RAY_BACKDROP_LUT',
        '#define RAY_BACKDROP_LUT 1',
        '#endif',
        '#if RAY_BACKDROP_LUT',
        'static const uint16_t ray_backdrop_row_offset[128] = {',
        *('    '+','.join(str(v) for v in offsets[i:i+16])+',' for i in range(0,128,16)),
        '};',
        'static const uint8_t ray_backdrop_pair_mask[128] = {',
        *('    '+','.join(str(v-1) for v in periods[i:i+16])+',' for i in range(0,128,16)),
        '};',
        'static const uint16_t ray_backdrop_lut[826] = {',
        *('    '+','.join(f'0x{v:04x}u' for v in packed[i:i+12])+',' for i in range(0,len(packed),12)),
        '};',
        'static inline uint16_t ray_backdrop_lut_word(uint8_t y,uint8_t pair) {',
        '    return ray_backdrop_lut[ray_backdrop_row_offset[y]+(pair&ray_backdrop_pair_mask[y])];',
        '}',
        '#endif',
        '#endif', '',
    ]
    return '\n'.join(c)


def main():
    p = argparse.ArgumentParser(); p.add_argument('--check', action='store_true'); a = p.parse_args()
    data = generate()
    if a.check:
        if not OUT.exists() or OUT.read_text() != data:
            raise SystemExit('backdrop shader is stale')
        print('BAT backdrop shader current; 128 rows of sky/ground, no planar upload')
    else:
        OUT.write_text(data)
        print(OUT)

if __name__ == '__main__':
    main()
