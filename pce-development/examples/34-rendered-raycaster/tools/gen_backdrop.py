#!/usr/bin/env python3
"""Generate a lossless row-deduplicated paired-BAT backdrop.

The background holds 128 * 64 BAT words, but many rows are identical.
Store unique rows and a byte index; this saves ROM without using precious RAM.
"""
from pathlib import Path
import argparse

ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/'src'/'backdrop_words.h'

def floor_color(u,v):
    if (u&31)==0 or (v&31)==0:return 7
    return 5 if (((u>>4)^(v>>4))&1) else 6

def original_rows():
    rows=[]
    camera=((3*256+128)>>5)&255
    for y in range(128):
        vals=[]
        for pair in range(64):
            if y<64:
                sky=0 if y<16 else 1 if y<32 else 2 if y<48 else 3
                val=(sky<<4)|sky
            else:
                shift=0 if y<66 else 4 if y<73 else 3 if y<82 else 2 if y<101 else 1
                fu=((pair<<shift)+camera)&255
                fv=((y<<shift)+camera)&255
                delta=(8 if shift==4 else 1<<(shift-1) if shift else 1)
                val=(floor_color(fu,fv)<<4)|floor_color((fu+delta)&255,fv)
            vals.append(0xf200|val)
        rows.append(vals)
    return rows

def compress(rows):
    unique=[];indices=[]
    for row in rows:
        if row not in unique:unique.append(row)
        indices.append(unique.index(row))
    return unique,indices

def generate():
    rows=original_rows();unique,indices=compress(rows)
    assert len(unique)<32 and all(unique[index]==rows[i] for i,index in enumerate(indices))
    lines=['/* Generated by tools/gen_backdrop.py. Lossless deduplicated 128x64 BAT. */',
           '#ifndef RAY_BACKDROP_WORDS_H','#define RAY_BACKDROP_WORDS_H',
           'static const uint8_t ray_backdrop_index[128] = {']
    for j in range(0,128,16):lines.append('    '+','.join(str(i) for i in indices[j:j+16])+',')
    lines+=['};',f'static const uint16_t ray_backdrop_unique[{len(unique)}][64] = {{']
    for row in unique: lines.append('    {'+','.join(f'0x{v:04x}u' for v in row)+'},')
    lines+=['};','#define ray_backdrop_row(y) (ray_backdrop_unique[ray_backdrop_index[(uint8_t)(y)]])','#endif','']
    return '\n'.join(lines)

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    data=generate()
    if a.check:
        if not OUT.exists() or OUT.read_text()!=data:raise SystemExit('backdrop table stale')
        print('backdrop generator: exact, 14 unique row templates, deterministic')
    else:
        OUT.write_text(data);print(OUT,OUT.stat().st_size)
if __name__=='__main__':main()
