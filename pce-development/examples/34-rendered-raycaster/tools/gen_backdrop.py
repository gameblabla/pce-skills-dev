#!/usr/bin/env python3
"""Generate a 128x64 paired-BAT sky/floor base (ROM, no runtime pixel shader).

Each cell is an actual VDC BAT word; this is an *initial-view, world-locked*
floor. During animation only wall spans are redrawn. No 32-bit target math.
"""
from pathlib import Path
import argparse

ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/'src'/'backdrop_words.h'

def floor_color(u,v):
    if (u&31)==0 or (v&31)==0:return 7
    return 5 if (((u>>4)^(v>>4))&1) else 6

def generate():
    rows=[]
    # initial player position in Q8, matches main.c: 3*256+128
    camera= ((3*256+128)>>5)&255
    for y in range(128):
        vals=[]
        for pair in range(64):
            if y<64:
                sky=0 if y<16 else 1 if y<32 else 2 if y<48 else 3
                val=(sky<<4)|sky
            else:
                # same five-step floor shift as ray_tables.h generated values
                shift=0 if y<66 else 4 if y<73 else 3 if y<82 else 2 if y<101 else 1
                fu=((pair<<shift)+camera)&255
                fv=((y<<shift)+camera)&255
                delta= (8 if shift==4 else 1<<(shift-1) if shift else 1)
                val=(floor_color(fu,fv)<<4)|floor_color((fu+delta)&255,fv)
            vals.append(0xf200|val)
        rows.append(vals)
    lines=['/* Generated by tools/gen_backdrop.py. 128x64 BASE BAT words. */',
           '#ifndef RAY_BACKDROP_WORDS_H','#define RAY_BACKDROP_WORDS_H',
           'static const uint16_t ray_backdrop[128][64] = {']
    for row in rows:
        lines.append('  {' + ','.join(f'0x{v:04x}u' for v in row) + '},')
    lines+=['};','#endif','']
    return '\n'.join(lines)

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    data=generate()
    if a.check:
        if not OUT.exists() or OUT.read_text()!=data:raise SystemExit('backdrop table stale')
        print('backdrop generator: exact, deterministic')
    else:
        OUT.write_text(data);print(OUT,OUT.stat().st_size)
if __name__=='__main__':main()
