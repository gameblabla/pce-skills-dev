#!/usr/bin/env python3
"""Generate palette pair quantization and 32-event BAT row skip IRQ."""
from pathlib import Path
import argparse
ROOT=Path(__file__).resolve().parent.parent
RGB=[(0,0,2),(0,0,3),(0,0,4),(2,2,2),(1,1,1),(2,2,1),
     (3,2,1),(4,4,4),(5,5,5),(3,0,0),(5,0,0),(4,0,1),
     (2,0,2),(5,5,0),(3,3,3),(0,0,0)]
# Greedy two-color pairs trained on six deterministic reference captures from
# the original 16-color renderer; fixed here for fully offline reproducibility.
PAIRS=[(1,5),(3,9),(4,14),(6,12),(0,2),(5,15),(4,9),(4,5),
       (3,14),(5,6),(3,12),(9,14),(4,6),(4,12),(3,4),(12,14)]
def distance(a,b):return sum((x-y)**2 for x,y in zip(RGB[a],RGB[b]))
def quant():
    q=[[int(distance(c,b)<distance(c,a)) for c in range(16)] for a,b in PAIRS]
    error=[[min(distance(c,a),distance(c,b)) for c in range(16)] for a,b in PAIRS]
    best=[min(range(16),key=lambda g:error[g][i>>4]+error[g][i&15]) for i in range(256)]
    lines=['/* GENERATED by tools/gen_pageflip_tiled.py -- lossily quantized 2-color pairs. */',
           '#ifndef RAY_TILED_QUANT_H','#define RAY_TILED_QUANT_H']
    for name,rows,suffix in [('ray_tiled_palettes',PAIRS,'[16][2]'),('ray_tiled_quant',q,'[16][16]'),('ray_tiled_error',error,'[16][16]')]:
        lines.append(f'static const uint8_t {name}{suffix} = {{')
        for row in rows:lines.append('    {'+','.join(str(x) for x in row)+'},')
        lines.append('};')
    lines.append('static const uint8_t ray_tiled_best_pair[256] = {')
    for x in range(0,256,16):lines.append('    '+','.join(str(t) for t in best[x:x+16])+',')
    lines+=['};','#endif']
    return '\n'.join(lines)+'\n'
def irq():
    b=['/* GENERATED 32-event scroll IRQ; two full 128x128 BAT pages. */',
       '.section .text.irq_vdc,"ax",@progbits', '.global irq_vdc', '.type irq_vdc,@function',
       '.extern bat_frames,bat_source_y,ray_flip_front,ray_flip_pending,ray_redraws',
       'irq_vdc:','    pha','    phx','    cld','    lda $0000','    pha',
       '    and #$20', '    beq .Lraster',
       '    inc bat_frames','    stz bat_source_y',
       '    lda ray_flip_pending','    beq .Lno_swap',
       '    stz ray_flip_pending','    lda ray_flip_front', '    eor #1','    sta ray_flip_front',
       '    inc ray_redraws', '    bne .Lno_swap', '    inc ray_redraws+1',
       '.Lno_swap:',
       '    st0 #7','    st1 #0','    lda ray_flip_front','    beq .Lfirst',
       '    st2 #2', '    bra .Lpositioned',
       '.Lfirst:', '    st2 #0',
       '.Lpositioned:',
       '    st0 #8','    st1 #0','    st2 #0',
       '    st0 #6','    st1 #$48', '    st2 #0',
       '.Lraster:', '    pla', '    and #$04', '    beq .Ldone',
       '    ldx bat_source_y', '    cpx #31', '    bcs .Ldone',
       '    inx', '    stx bat_source_y',
       '    st0 #8','    lda tiled_byr_low,x','    sta $0002',
       '    lda tiled_byr_high,x','    sta $0003',
       '    st0 #6','    lda tiled_rcr_low,x','    sta $0002',
       '    lda tiled_rcr_high,x','    sta $0003',
       '.Ldone:', '    plx','    pla','    rti','.size irq_vdc, .-irq_vdc',
       '.section .rodata.irq_tables,"a",@progbits']
    arr={
        'tiled_byr_low':[(8*i-1)&255 for i in range(32)],
        'tiled_byr_high':[((8*i-1)>>8)&255 for i in range(32)],
        'tiled_rcr_low':[(0x41+7*(i+1))&255 for i in range(32)],
        'tiled_rcr_high':[((0x41+7*(i+1))>>8)&255 for i in range(32)],
    }
    for name,vals in arr.items():
        b.append(name+':')
        for i in range(0,len(vals),16):b.append('    .byte '+','.join(f'${v&255:02x}' for v in vals[i:i+16]))
    return '\n'.join(b)+'\n'
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    files=[(ROOT/'src'/'pageflip_tiled_quant.h',quant()),(ROOT/'src'/'bat_pageflip_tiled_irq.S',irq())]
    for f,s in files:
        if a.check:
            if not f.exists() or f.read_text()!=s:raise SystemExit(str(f)+' is stale')
        else:f.write_text(s)
