#!/usr/bin/env python3
"""Exhaustively check the generated wall LUT against the original C shader.

Each material (including face-darkening), depth 1..32, U and texture V
phase is tested. This is the *exact palette-index* comparison, not an image
similarity metric that could overlook lost texture detail or wrong colours.
"""
import gen_wall_pairs as lut


def original_pixel(material, depth, face, u, v):
    if material == 3:
        if u == 0 or (v & 7) == 0:
            return 7
        return 15 if ((u+v)&3) == 0 else 11
    if material == 2:
        if (v&3) == 0 or ((u+(4 if v&4 else 0))&7) == 0:
            return 7
        return 8 if depth > 13 else (10 if ((u^v)&2) else 9)
    if (v&7) == 0 or ((u+(3 if v&8 else 0))&7) == 0:
        return 7
    if depth > 16 or face:
        return 12
    return 15 if ((u^v)&3) == 0 else 13


def style(material, depth, face):
    if material == 3:return 4
    if material == 2:return 3 if depth>13 else 2
    return 1 if depth>16 or face else 0


def verify():
    count=0
    for material in (1,2,3):
        for depth in range(1,33):
            for face in (0,1):
                st=style(material,depth,face)
                for u in range(8):
                    for v in range(16):
                        expected=original_pixel(material,depth,face,u,v)*16+original_pixel(material,depth,face,(u+1)&7,v)
                        found=lut.pair(st,u,v)
                        if found!=expected:
                            raise ValueError(f'wall shader mismatch at {(material,depth,face,u,v)}: {found:#04x}!={expected:#04x}')
                        count+=1
    if len(lut.generate().splitlines()) < 50:
        raise ValueError('missing shader table rows')
    return count


if __name__=='__main__':
    print(f'{verify()} reference wall-pair cases passed; 640 generated bytes')
