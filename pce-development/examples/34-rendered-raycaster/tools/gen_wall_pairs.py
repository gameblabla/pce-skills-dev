#!/usr/bin/env python3
"""Generate exact paired 4-bit wall texels offline, without HuC6280 mul/div.

Five lighting/material classes encode the existing stone, brick and metal
shaders. Columns use 8 horizontal phases and 16 vertical texture phases.
Lookup is 5*8*16 = 640 ROM bytes; indices are powers of two. The full-detail
This generator supplies reference 128x128 wall shading tables.
"""
import argparse
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[1] / 'src' / 'wall_pairs.h'
STYLE_NAMES = ('stone_lit', 'stone_shaded', 'brick_lit', 'brick_distant', 'metal')


def pixel(style, u, v):
    assert 0 <= style < 5 and 0 <= u < 8 and 0 <= v < 16
    if style == 4:
        if u == 0 or (v & 7) == 0:
            return 7
        return 15 if ((u + v) & 3) == 0 else 11
    if style in (2, 3):
        if (v & 3) == 0 or ((u + (4 if v & 4 else 0)) & 7) == 0:
            return 7
        return 8 if style == 3 else (10 if ((u ^ v) & 2) else 9)
    if (v & 7) == 0 or ((u + (3 if v & 8 else 0)) & 7) == 0:
        return 7
    if style == 1:
        return 12
    return 15 if ((u ^ v) & 3) == 0 else 13


def pair(style, u, v):
    return pixel(style, u, v) * 16 + pixel(style, (u + 1) & 7, v)


def generate():
    lines = ['/* Generated by tools/gen_wall_pairs.py; do not hand-edit. */',
             '#ifndef PCE_RAY_WALL_PAIRS_H', '#define PCE_RAY_WALL_PAIRS_H',
             '/* 5 x 8 x 16 = 640 bytes in ROM; indexing uses shifts only. */',
             'static const uint8_t ray_wall_pairs[5][8][16] = {']
    for style, name in enumerate(STYLE_NAMES):
        lines.append(f'    {{ /* {name} */')
        for u in range(8):
            lines.append('        {' + ','.join(f'0x{pair(style, u, v):02x}' for v in range(16)) + '},')
        lines.append('    },')
    lines.extend(['};', '#endif', ''])
    return '\n'.join(lines)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    expected = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            p.error('wall_pairs.h is missing/stale; run tools/gen_wall_pairs.py')
        print('640-byte paired wall LUT matches host shader')
    else:
        OUTPUT.write_text(expected)
        print(OUTPUT)


if __name__ == '__main__':
    main()
