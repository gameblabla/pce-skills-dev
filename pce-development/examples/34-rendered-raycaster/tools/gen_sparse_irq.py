#!/usr/bin/env python3
"""Generate sparse HuC6280 IRQ assembly: 127 logical row transitions / frame.

All BAT glyphs are vertically uniform, so repeating a logical row across two
physical scanlines does not require an IRQ on the intervening scanline.
The second BAT half uses a one-row circular rotation to ensure the BXR
page switch cannot expose its bottom-floor row while BYR catches up.
"""
from pathlib import Path
import argparse
ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/'src'/'bat_sparse_irq.S'
NATURAL_OUT=ROOT/'src'/'bat_natural_irq.S'

def bat_row(y):
    """Place row 64 in the previous BYR position across the page flip."""
    if not 0 <= y < 128:
        raise ValueError('logical bitmap row out of range')
    return ((y-1) if y>=64 else y)&63


def gen(legacy=False):
    b=['/* GENERATED by tools/gen_sparse_irq.py. Do not edit by hand. */',
       '.section .text.irq_vdc,"ax",@progbits','.global irq_vdc','.type irq_vdc,@function',
       '.extern bat_frames,bat_source_y',
       'irq_vdc:', '    pha','    phx','    cld',
       '    lda $0000', '    pha', '    and #$20', '    beq .Lraster',
       '    inc bat_frames','    stz bat_source_y',
       '    st0 #7', '    st1 #0', '    st2 #0',
       '    st0 #8', '    st1 #0', '    st2 #0',
       '    st0 #6', '    st1 #$43', '    st2 #0',
       '.Lraster:', '    pla', '    and #$04', '    beq .Ldone',
       '    ldx bat_source_y', '    cpx #127', '    bcs .Ldone',
       '    inx', '    stx bat_source_y',
       '    cpx #64', '    bne .Lno_page',
       '    st0 #7', '    st1 #0', '    st2 #2',
       '.Lno_page:',
       '    st0 #8', '    lda irq_byr_low,x', '    sta $0002',
       '    lda irq_byr_high,x', '    sta $0003',
       '    st0 #6', '    inx',
       '    lda irq_rcr_low,x', '    sta $0002',
       '    lda irq_rcr_high,x', '    sta $0003',
       '.Ldone:', '    plx','    pla','    rti',
       '.size irq_vdc, .-irq_vdc']
    # Reproduce the previous Y-indexed IRQ for same-source cycle and raster
    # comparisons; all four scroll/scanline lookup tables remain unchanged.
    if legacy:
        b.insert(b.index('    phx')+1,'    phy')
        at=b.index('    ldx bat_source_y')
        b[at:at+5]=['    lda bat_source_y', '    cmp #127',
                    '    bcs .Ldone', '    inc bat_source_y',
                    '    ldy bat_source_y']
        b[b.index('    cpx #64')]='    cpy #64'
        b[b.index('    inx')]='    iny'
        for t in ('irq_byr_low','irq_byr_high','irq_rcr_low','irq_rcr_high'):
            b[b.index('    lda '+t+',x')]='    lda '+t+',y'
        b.insert(b.index('    plx'),'    ply')
    # The last y=127 has an out-of-range RCR value (0x1ff).
    arr={
        # Reuse the preceding BAT-row scroll at the 64/65 page switch.
        # BXR can become effective a scanline before BYR on the HuC6270.
        # Rotating page 2 means both the stale and new BYR resolve to its
        # intended first row, eliminating the otherwise visible floor stripe.
        'irq_byr_low':[(bat_row(y)*8-1)&255 if y<128 else 0xff for y in range(129)],
        'irq_byr_high':[((bat_row(y)*8-1)>>8)&255 if y<128 else 0xff for y in range(129)],
        'irq_rcr_low':[(0x41+((y*7+3)//4))&255 if y<128 else 0xff for y in range(129)],
        'irq_rcr_high':[(0x41+((y*7+3)//4))>>8 if y<128 else 1 for y in range(129)],
    }
    b += ['.section .rodata.irq_tables,"a",@progbits']
    for name,v in arr.items():
        b.append(name+':')
        for i in range(0,len(v),16):b.append('    .byte '+','.join(f'${x&255:02x}' for x in v[i:i+16]))
    return '\n'.join(b)+'\n'


def natural_next(y):
    """Next *IRQ* source row; intervening odd rows use BYR auto-increment."""
    if y == 0: return 1
    if y == 1: return 2
    if (2 <= y < 60 or 68 <= y <= 126) and not (y & 1): return y+2
    return min(y+1,128)


def natural_offset(y):
    # After a write, the VDC uses BYR+1. Start even two-line rows at
    # tile offset 6; the automatic 7 -> 0 carry displays the next row.
    # Keep every raster event around logical y=60..68 and the BXR seam.
    if (2 <= y < 60 or 68 <= y <= 126) and not (y & 1):
        return bat_row(y)*8+5
    return bat_row(y)*8-1


def gen_natural():
    b=['/* GENERATED by tools/gen_sparse_irq.py -- natural-scroll IRQ. */',
       '.section .text.irq_vdc,"ax",@progbits', '.global irq_vdc',
       '.type irq_vdc,@function', '.extern bat_frames,bat_source_y',
       'irq_vdc:', '    pha', '    phx', '    cld', '    lda $0000',
       '    pha', '    and #$20', '    beq .Lraster',
       '    inc bat_frames', '    stz bat_source_y',
       '    st0 #7', '    st1 #0', '    st2 #0',
       '    st0 #8', '    st1 #0', '    st2 #0',
       '    st0 #6', '    st1 #$43', '    st2 #0',
       '.Lraster:', '    pla', '    and #$04', '    beq .Ldone',
       '    ldx bat_source_y', '    cpx #126', '    bcs .Ldone',
       # BXR switches at event y=64. Use the index *before* loading next.
       '    cpx #63', '    bne .Lno_page',
       '    st0 #7', '    st1 #0', '    st2 #2',
       '.Lno_page:', '    lda irq_next,x', '    tax',
       '    stx bat_source_y',
       '    st0 #8', '    lda irq_byr_low,x', '    sta $0002',
       '    lda irq_byr_high,x', '    sta $0003',
       '    st0 #6', '    lda irq_rcr_low,x', '    sta $0002',
       '    lda irq_rcr_high,x', '    sta $0003',
       '.Ldone:', '    plx', '    pla', '    rti',
       '.size irq_vdc, .-irq_vdc',
       '.section .rodata.irq_tables,"a",@progbits']
    arr={
        'irq_next': [natural_next(y) if y<127 else 128 for y in range(128)],
        'irq_byr_low': [natural_offset(y)&255 for y in range(128)],
        'irq_byr_high': [(natural_offset(y)>>8)&255 for y in range(128)],
        'irq_rcr_low': [(0x41+((natural_next(y)*7+3)//4))&255 for y in range(128)],
        'irq_rcr_high': [((0x41+((natural_next(y)*7+3)//4))>>8)&255 for y in range(128)],
    }
    for name,values in arr.items():
        b.append(name+':')
        for i in range(0,len(values),16):
            b.append('    .byte '+','.join(f'${v:02x}' for v in values[i:i+16]))
    return '\n'.join(b)+'\n'

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');p.add_argument('--legacy-output',type=Path);p.add_argument('--natural-output',type=Path);a=p.parse_args()
    content=gen()
    if a.legacy_output:
        a.legacy_output.parent.mkdir(parents=True,exist_ok=True)
        a.legacy_output.write_text(gen(legacy=True))
        print(a.legacy_output)
    elif a.natural_output:
        a.natural_output.parent.mkdir(parents=True,exist_ok=True)
        a.natural_output.write_text(gen_natural())
        print(a.natural_output)
    elif a.check:
        if not OUT.exists() or OUT.read_text()!=content:raise SystemExit('sparse IRQ source stale')
        if not NATURAL_OUT.exists() or NATURAL_OUT.read_text()!=gen_natural():raise SystemExit('natural-scroll IRQ source stale')
        print('standard and natural-scroll IRQ byte tables match generated schedules')
    else:
        OUT.write_text(content);NATURAL_OUT.write_text(gen_natural())
        print(OUT,NATURAL_OUT)
if __name__=='__main__':main()
