#!/usr/bin/env python3
"""Generate sparse HuC6280 IRQ assembly: 127 logical row transitions / frame.

All BAT glyphs are vertically uniform, so repeating a logical row across two
physical scanlines does not require an IRQ on the intervening scanline.
"""
from pathlib import Path
import argparse
ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/'src'/'bat_sparse_irq.S'

def gen():
    b=['/* GENERATED by tools/gen_sparse_irq.py. Do not edit by hand. */',
       '.section .text.irq_vdc,"ax",@progbits','.global irq_vdc','.type irq_vdc,@function',
       '.extern bat_frames,bat_source_y',
       'irq_vdc:', '    pha','    phx','    phy','    cld',
       '    lda $0000', '    pha', '    and #$20', '    beq .Lraster',
       '    inc bat_frames','    stz bat_source_y',
       '    st0 #7', '    st1 #0', '    st2 #0',
       '    st0 #8', '    st1 #0', '    st2 #0',
       '    st0 #6', '    st1 #$43', '    st2 #0',
       '.Lraster:', '    pla', '    and #$04', '    beq .Ldone',
       '    lda bat_source_y', '    cmp #127', '    bcs .Ldone',
       '    inc bat_source_y', '    ldy bat_source_y',
       '    cpy #64', '    bne .Lno_page',
       '    st0 #7', '    st1 #0', '    st2 #2',
       '.Lno_page:',
       '    st0 #8', '    lda irq_byr_low,y', '    sta $0002',
       '    lda irq_byr_high,y', '    sta $0003',
       '    st0 #6', '    iny',
       '    lda irq_rcr_low,y', '    sta $0002',
       '    lda irq_rcr_high,y', '    sta $0003',
       '.Ldone:', '    ply','    plx','    pla','    rti',
       '.size irq_vdc, .-irq_vdc']
    # The last y=127 has an out-of-range RCR value (0x1ff).
    arr={
        'irq_byr_low':[((y&63)*8-1)&255 for y in range(129)],
        'irq_byr_high':[((y&63)*8-1)>>8&255 for y in range(129)],
        'irq_rcr_low':[(0x41+((y*7+3)//4))&255 if y<128 else 0xff for y in range(129)],
        'irq_rcr_high':[(0x41+((y*7+3)//4))>>8 if y<128 else 1 for y in range(129)],
    }
    b += ['.section .rodata.irq_tables,"a",@progbits']
    for name,v in arr.items():
        b.append(name+':')
        for i in range(0,len(v),16):b.append('    .byte '+','.join(f'${x&255:02x}' for x in v[i:i+16]))
    return '\n'.join(b)+'\n'

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    content=gen()
    if a.check:
        if not OUT.exists() or OUT.read_text()!=content:raise SystemExit('sparse IRQ source stale')
        print('sparse IRQ byte tables match exact 7:4 logical/physical schedule')
    else:OUT.write_text(content);print(OUT)
if __name__=='__main__':main()
