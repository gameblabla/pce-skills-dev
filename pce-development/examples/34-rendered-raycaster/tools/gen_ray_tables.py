#!/usr/bin/env python3
"""Generate the 32-ray Q8 step table for the tiny HuC6280 raycaster.

All non-power-of-two divisions/multiplications happen on the host. The target
only adds signed 8-bit Q8 steps, uses fixed lookup heights and shifts indices.
Check the generated header offline with --check before building the ROM.
"""
import argparse
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / 'src' / 'ray_tables.h'
COS=(127,117,90,49,0,-49,-90,-117,-127,-117,-90,-49,0,49,90,117)
SIN=(0,49,90,117,127,117,90,49,0,-49,-90,-117,-127,-117,-90,-49)

def truncdiv(a,b):
    return (abs(a)//b) * (-1 if a<0 else 1)

def generate():
    out=['/* Generated by tools/gen_ray_tables.py. Do not hand-edit. */',
         '#ifndef PCE_RAY_TABLES_H','#define PCE_RAY_TABLES_H']
    for axis in ('x','y'):
        out.append(f'static const int8_t ray_step_{axis}[16][32] = {{')
        for a in range(16):
            values=[]
            for col in range(32):
                side=col-16
                dx=COS[a]-truncdiv(SIN[a]*side,40)
                dy=SIN[a]+truncdiv(COS[a]*side,40)
                values.append(truncdiv(dx if axis=='x' else dy,2))
            if any(not -128<=v<=127 for v in values):raise ValueError('signed ray step overflow')
            out.append('    {'+','.join(str(v) for v in values)+'},')
        out.append('};')
    for axis,source in (('x',COS),('y',SIN)):
        out.append(f'static const int8_t player_step_{axis}[16] = '+'{'+','.join(str(truncdiv(v,6)) for v in source)+'};')
    # Logical 128-pixel-high wall; texture V is an indexed 16-pixel pattern.
    heights=[max(12,min(116,360//(d+2))) for d in range(33)]
    out.append('static const uint8_t wall_height[33] = {'+','.join(map(str,heights))+'};')
    out.append('static const uint8_t wall_tex_v[33][64] = {')
    for h in heights:
        out.append('    {'+','.join(str((k*32)//h if (k*2)<h else 0) for k in range(64))+'},')
    out.append('};')
    out.append('static const uint8_t floor_shift[128] = {'+','.join(
        str(0 if y<66 else 4 if y<73 else 3 if y<82 else 2 if y<101 else 1)
        for y in range(128))+'};')
    out.extend(['#endif',''])
    return '\n'.join(out)

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check',action='store_true')
    args=ap.parse_args();expected=generate()
    if args.check:
        if not OUT.exists() or OUT.read_text()!=expected:
            ap.error('ray_tables.h is missing or stale; run tools/gen_ray_tables.py')
        print('ray projection tables match host arithmetic reference')
    else:
        OUT.write_text(expected)
        print(OUT)

if __name__=='__main__':main()
