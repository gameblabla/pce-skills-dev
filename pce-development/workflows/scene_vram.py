#!/usr/bin/env python3
"""Cross-check actual scene_pack assets with HuC6270 VRAM layout and upload budget.

Consumes scene_assets.h + scene_manifest.json generated by scene_pack.py.
Catches stale BAT, pattern or sprite sizes and overlapping VRAM allocations.
Initial uploads are a planning scenario; ROM boot is not constrained to the
frame budget used here, and dynamic SAT writes are checked separately.
"""
import argparse
import json
from pathlib import Path
import re
from vram_budget import plan


def header_number(header, symbol):
    match=re.search(r'^#define\s+'+re.escape(symbol)+r'\s+(0x[\da-fA-F]+|\d+)u?\s*$',header,re.M)
    if not match:raise ValueError(f'{symbol}: missing address in scene_assets.h')
    return int(match.group(1),0)


def array_size(header, name):
    match=re.search(r'\b'+re.escape(name)+r'\[(\d+)\]',header)
    if not match:raise ValueError(f'{name}: missing byte count in scene_assets.h')
    return int(match.group(1))


def analyze(project,bytes_per_frame=768,max_frames=32):
    project=Path(project)
    source=project/'src'
    manifest=json.loads((source/'scene_manifest.json').read_text())
    header=(source/'scene_assets.h').read_text()
    if manifest.get('format')!='pce-scene-pack-v1':raise ValueError('unknown scene manifest format')
    vram=manifest.get('vram_word_ranges')
    if not isinstance(vram,dict) or set(vram)!={'bat','bg','sprites','sat'}:
        raise ValueError('manifest needs bat,bg,sprites,sat allocations')
    regions=[]
    for name,pair in vram.items():
        if not isinstance(pair,list) or len(pair)!=2 or any(type(x)!=int for x in pair) or pair[1]<=pair[0]:
            raise ValueError(f'{name}: invalid word range')
        regions.append({'id':name,'start_word':pair[0],'words':pair[1]-pair[0]})
    actual={'bat':(0,array_size(header,'scene_bat')),
            'bg':(header_number(header,'SCENE_BG_WORD'),array_size(header,'scene_patterns')),
            'sprites':(header_number(header,'SCENE_SPRITE_WORD'),array_size(header,'scene_sprites'))}
    if header_number(header,'SCENE_SAT_WORD')!=vram['sat'][0]:
        raise ValueError('SAT macro and manifest address disagree')
    for name,(start,nbytes) in actual.items():
        if start!=vram[name][0]:raise ValueError(f'{name}: manifest and C header VRAM start differ')
        if nbytes<1 or nbytes&1 or start+nbytes//2>vram[name][1]:
            raise ValueError(f'{name}: array size overflows manifest allocation')
        if name!='bat' and start+nbytes//2!=vram[name][1]:
            raise ValueError(f'{name}: manifest pattern allocation does not match C byte count')
    if manifest.get('unique_tiles')*32!=actual['bg'][1]:
        raise ValueError('background unique tile count does not match packed 4bpp patterns')
    if manifest.get('sprite_frames')*128!=actual['sprites'][1]:
        raise ValueError('sprite frames do not match 16x16 4bpp byte count')
    # Initial scene transfer before display enabling; distinct from ongoing SAT publication.
    uploads=[{'id':'boot-'+k,'region':k,'bytes':nbytes,'deadline_frame':max_frames-1}
             for k,(_,nbytes) in actual.items()]
    uploads.append({'id':'boot-sat','region':'sat','bytes':512,'deadline_frame':max_frames-1})
    report=plan({'system':'pce','bytes_per_frame':bytes_per_frame,'max_frames':max_frames,
                 'max_chunk_bytes':16,'raster_irqs':True,
                 'regions':regions,'uploads':uploads})
    return {'ok':report['ok'],'project':str(project),
            'scene_arrays_bytes':{key:value[1] for key,value in actual.items()},
            'reserved_words':{r['id']:r['words'] for r in regions},
            'boot_upload':report,'limits':'Initial-load budget is an explicit assumption; not hardware VBlank profiling.'}


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('project',type=Path)
    ap.add_argument('--bytes-per-frame',type=int,default=768)
    ap.add_argument('--max-frames',type=int,default=32)
    ap.add_argument('--output',type=Path)
    args=ap.parse_args()
    try:r=analyze(args.project,args.bytes_per_frame,args.max_frames)
    except (ValueError,OSError,TypeError) as e:ap.error(str(e))
    content=json.dumps(r,indent=2)+'\n'
    if args.output:
        args.output.parent.mkdir(parents=True,exist_ok=True)
        args.output.write_text(content)
    else:
        print(json.dumps({k:v for k,v in r.items() if k!='boot_upload'},indent=2))
        print('boot transfer frames:',r['boot_upload']['frames_used'],'completed:',r['ok'])
    return 0 if r['ok'] else 1

if __name__=='__main__':raise SystemExit(main())
