#!/usr/bin/env python3
"""Offline-generated Mode7 projection coefficients; never generate these on PCE."""
from pathlib import Path
import argparse

DEPTH = [1408 // (y-27) for y in range(35,128)]
COEFF = [0,49,90,117,127]

def make():
    out=['/* GENERATED by tools/gen_mode7_lut.py; do not hand-edit. */',
         '#ifndef PCE_MODE7_LUT_H', '#define PCE_MODE7_LUT_H']
    for i,c in enumerate(COEFF):
        values=[str(c*d) for d in DEPTH]
        out.append('static const uint16_t pce_m7_lut_'+str(i)+'[93] = {')
        for k in range(0,len(values),12):out.append('    '+', '.join(values[k:k+12])+',')
        out.append('};')
    out.append('#endif')
    return '\n'.join(out)+'\n'

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    dest=Path(__file__).resolve().parents[1]/'src/mode7_lut.h'
    content=make()
    if a.check:
        if not dest.exists() or dest.read_text()!=content:
            raise SystemExit('stale Mode7 table: python3 tools/gen_mode7_lut.py')
        print('Mode7 table verified')
    else:dest.write_text(content)
if __name__=='__main__':main()
